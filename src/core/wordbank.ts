/**
 * 解析导入文本，每行一个词：
 *   word
 *   word /音标/ 释义
 *   word 释义
 *   word,释义 或 word<Tab>释义
 */
export function parseWordLines(text: string): WordSeed[] {
  const seen = new Set<string>()
  const out: WordSeed[] = []
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim()
    if (!line) continue
    // 先按逗号 / 制表符切出释义
    let body = line
    let meaning = ''
    const tabIdx = body.search(/[\t，,]/)
    if (tabIdx > 0) {
      meaning = body.slice(tabIdx + 1).trim()
      body = body.slice(0, tabIdx).trim()
    }
    // 音标：/.../ 或 [...] 形式
    let phonetic = ''
    const ph = body.match(/(\/[^/]+\/|\[[^\]]+\])/)
    if (ph) {
      phonetic = ph[1]
      body = (body.slice(0, ph.index) + ' ' + body.slice((ph.index ?? 0) + ph[1].length)).trim()
      // 音标后若还有剩余文本且释义为空，当释义
      if (!meaning && body.split(/\s+/).length > 1) {
        const parts = body.split(/\s+/)
        meaning = parts.slice(1).join(' ')
        body = parts[0]
      }
    }
    // 余下的第一个 token 是单词，后面若还有内容且没释义就当释义
    const tokens = body.split(/\s+/).filter(Boolean)
    if (tokens.length === 0) continue
    const word = tokens[0].replace(/^[^A-Za-z'-]+|[^A-Za-z'-]+$/g, '').toLowerCase()
    if (!word || !/^[a-z][a-z'-]*$/.test(word)) continue
    if (!meaning && tokens.length > 1) meaning = tokens.slice(1).join(' ')
    if (seen.has(word)) continue
    seen.add(word)
    out.push({ word, phonetic: phonetic || undefined, meaning: meaning || undefined })
  }
  return out
}
