/** 同一天永远是同一首：按自然日序号取模，换设备、重装也一致 */
export function poemOfDay(key: DateKey): Poem {
  const [y, m, d] = key.split('-').map(Number)
  const days = Math.floor(Date.UTC(y, m - 1, d) / 86400000)
  return POEMS[((days % POEMS.length) + POEMS.length) % POEMS.length]
}
